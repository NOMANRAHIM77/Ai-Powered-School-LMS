import assert from 'node:assert/strict';
import { test } from 'node:test';
import express from 'express';
import sharp from 'sharp';
import { Types } from 'mongoose';
import { User } from '../src/models/User';
import { Teacher } from '../src/models/Teacher';
import { Student } from '../src/models/Student';
import { AcademicYear } from '../src/models/AcademicYear';
import { Class } from '../src/models/Class';
import { Section } from '../src/models/Section';
import { Enrollment } from '../src/models/Enrollment';
import { Course } from '../src/models/Course';
import { wingForClass } from '../src/utils/schoolWings';
import { standardSectionNames } from '../src/utils/standardSections';
import { generateAccessToken } from '../src/utils/tokens';
import { errorHandler } from '../src/middleware/errorHandler';
import routes from '../src/routes/adminUsers.routes';
import * as identity from '../src/utils/studentIdentity';

test('only admins can create validated accounts and responses never return password hashes', async () => {
  const originalIdentity = identity.nextStudentIdentity; (identity as any).nextStudentIdentity = async () => 'pri-gen-8-0001-A';
  const originals = { findById: User.findById, exists: User.exists, create: User.create, teacherExists: Teacher.exists, teacherCreate: Teacher.create, studentExists: Student.exists, studentCreate: Student.create, yearFind: AcademicYear.findOne, classFind: Class.find, sectionFind: Section.find };
  const adminId = new Types.ObjectId();
  const oldCourse = { exists: Course.exists, update: Course.findOneAndUpdate };
  const assignedCourses: any[] = [];
  (Course as any).exists = async () => null;
  (Course as any).findOneAndUpdate = async (_filter: any, update: any) => { assignedCourses.push(update); return {}; };
  const originalClassOne = Class.findOne; const originalSectionById = Section.findById; const originalEnrollmentCreate = Enrollment.create;
  const yearId = new Types.ObjectId(); const classId = new Types.ObjectId(); const sectionId = new Types.ObjectId(); const sectionId2 = new Types.ObjectId();
  let role = 'student';
  let teacherProfile: any;
  let studentProfile: any;
  (User as any).findById = () => ({ select: async () => ({ _id: adminId, role, isActive: true, name: 'Admin', email: 'admin@example.test' }) });
  (User as any).exists = async () => null;
  (Teacher as any).exists = async () => null;
  (Student as any).exists = async () => null;
  (User as any).create = async (value: any) => ({ ...value, _id: new Types.ObjectId() });
  (Teacher as any).create = async (value: any) => { teacherProfile = value; return { ...value, _id: new Types.ObjectId() }; };
  (Student as any).create = async (value: any) => { studentProfile = value; return { ...value, _id: new Types.ObjectId() }; };
  (Class as any).findOne = async () => ({ _id: classId, name: 'Grade 8', academicYearId: yearId });
  (Section as any).findById = async () => ({ _id: sectionId, classId, name: 'A' });
  (Enrollment as any).create = async (value: any) => value;
  (AcademicYear as any).findOne = async () => ({ _id: yearId });
  (Class as any).find = () => ({ select: () => ({ lean: async () => [{ _id: classId, name: 'Grade 8' }] }) });
  (Section as any).find = (query: any) => ({ select: () => ({ lean: async () => !query.classId || query.classId.$in.map(String).includes(String(classId)) ? query._id.$in.filter((id: string) => [String(sectionId), String(sectionId2)].includes(id)).map((_id: string) => ({ _id, classId, name: 'A' })) : [] }) });
  const app = express(); app.use(express.json()); app.use('/admin/users', routes); app.use(errorHandler);
  const server = app.listen(0, '127.0.0.1');
  try {
    await new Promise<void>(resolve => server.once('listening', resolve));
    const address = server.address(); assert.ok(address && typeof address !== 'string');
    const token = generateAccessToken({ _id: String(adminId), role: 'admin', name: 'Admin', email: 'admin@example.test' });
    const url = `http://127.0.0.1:${address.port}/admin/users`;
    const request = (body: unknown) => fetch(url, { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    const details = { role: 'teacher', name: 'Sara Ahmed', email: 'sara@example.test', password: 'long-test-password', employeeId: 'T-001', wing: 'primary', sectionIds: [String(sectionId), String(sectionId2)], subjectNames: ['Math'] };
    assert.equal((await request(details)).status, 403);
    role = 'admin';
    assert.equal((await request({ ...details, subjectNames: [] })).status, 400);
    assert.equal((await request({ ...details, subjectNames: ['Biology'] })).status, 400);
    assert.equal((await request({ ...details, password: '' })).status, 400);
    assert.equal((await request({ ...details, role: 'student' })).status, 400);
    assert.equal((await request({ role: 'admin', name: 'Sara Ahmed', email: 'sara@example.test', password: 'a' })).status, 201);
    const shortAdmin = await request({ role: 'admin', name: 'Admin Two', email: 'admin2@example.test', password: 'abcde' });
    assert.equal(shortAdmin.status, 201);
    const studentDetails = { role: 'student', parentName: 'Guardian', parentPhone: '03001234567', name: 'Ayesha Khan', email: 'student@example.test', password: 'a', admissionNo: 'S-001', dob: '2012-04-15', gender: 'female', wing: 'primary', sectionId: String(sectionId) };
    assert.equal((await request({ ...studentDetails, sectionId: undefined })).status, 400);
    assert.equal((await request({ ...studentDetails, wing: 'secondary' })).status, 400);
    const student = await request(studentDetails);
    assert.equal(student.status, 201);
    assert.equal(studentProfile.admissionNo, 'S-001');
    assert.equal(studentProfile.photo, undefined);
    const portrait = await sharp({ create: { width: 640, height: 480, channels: 3, background: '#224466' } }).png().toBuffer();
    const withPhoto = async (image: Buffer, type = 'image/png') => {
      const form = new FormData();
      for (const [key, value] of Object.entries(studentDetails)) form.append(key, value);
      form.append('photo', new Blob([new Uint8Array(image)], { type }), 'portrait.png');
      return fetch(url, { method: 'POST', headers: { Authorization: `Bearer ${token}` }, body: form });
    };
    assert.equal((await withPhoto(portrait)).status, 201);
    assert.match(studentProfile.photo, /^data:image\/webp;base64,/);
    const metadata = await sharp(Buffer.from(studentProfile.photo.split(',')[1], 'base64')).metadata();
    assert.equal(metadata.width, 320); assert.equal(metadata.height, 320);
    assert.equal(metadata.format, 'webp');
    assert.equal((await withPhoto(Buffer.from('not an image'))).status, 400);
    assert.equal((await withPhoto(portrait, 'application/pdf')).status, 400);
    const oversized = await withPhoto(Buffer.alloc(5 * 1024 * 1024 + 1));
    assert.equal(oversized.status, 400);
    assert.match((await oversized.json() as any).message, /5 MB/);
    assert.equal((await request({ ...details, wing: 'secondary' })).status, 400);
    assert.equal((await request({ ...details, sectionIds: [String(sectionId), String(sectionId)] })).status, 400);
    assert.equal((await request({ ...details, sectionIds: [String(new Types.ObjectId())] })).status, 400);
    const response = await request(details);
    assert.equal(response.status, 201);
    const body: any = await response.json();
    assert.equal(body.data.email, details.email);
    assert.equal(body.data.passwordHash, undefined);
    assert.equal(teacherProfile.employeeId, details.employeeId);
    assert.equal(teacherProfile.wing, 'primary');
    assert.deepEqual(teacherProfile.subjectNames, ['Math']); assert.equal(assignedCourses.length, 2);
    assert.deepEqual(teacherProfile.sectionIds, details.sectionIds);
    assert.equal(String(teacherProfile.assignmentAcademicYearId), String(yearId));
    assert.equal(wingForClass('Class 1'), 'primary');
    assert.equal(wingForClass('Grade 8'), 'primary');
    assert.equal(wingForClass('Grade 9'), 'secondary');
    assert.equal(wingForClass('10'), 'secondary');
    assert.equal(wingForClass('Class 11'), 'higher');
    assert.equal(wingForClass('Grade 12'), 'higher');
    assert.equal(wingForClass('Nursery'), null);
    assert.deepEqual(standardSectionNames(1), ['A', 'B', 'C', 'D']);
    assert.deepEqual(standardSectionNames(8), ['A', 'B', 'C', 'D']);
    assert.deepEqual(standardSectionNames(9).filter(name => name.startsWith('Pre-Engineering')), ['Pre-Engineering - A', 'Pre-Engineering - B', 'Pre-Engineering - C', 'Pre-Engineering - D']);
    assert.equal(standardSectionNames(12).length, 16);
    assert.ok(standardSectionNames(12).includes('Computer Science - D'));
    assert.ok(standardSectionNames(12).includes('Medical - A'));
    assert.ok(standardSectionNames(12).includes('Humanities - C'));
  } finally {
    (identity as any).nextStudentIdentity = originalIdentity;
    (Course as any).exists = oldCourse.exists; (Course as any).findOneAndUpdate = oldCourse.update;
    await new Promise<void>(resolve => server.close(() => resolve()));
    (User as any).findById = originals.findById; (User as any).exists = originals.exists; (User as any).create = originals.create;
    (Teacher as any).exists = originals.teacherExists; (Teacher as any).create = originals.teacherCreate;
    (Student as any).exists = originals.studentExists; (Student as any).create = originals.studentCreate;
    (AcademicYear as any).findOne = originals.yearFind; (Class as any).find = originals.classFind; (Section as any).find = originals.sectionFind;
    (Class as any).findOne = originalClassOne; (Section as any).findById = originalSectionById; (Enrollment as any).create = originalEnrollmentCreate;
  }
});

